// apps/api/src/native/native-hooks.ts
// The static files a native session's harness is launched with
// (docs/specs/2026-10-05-native-sessions.md, docs/specs/2026-10-16-native-codex.md). All are
// passed as LAUNCH ARGUMENTS — claude's `--settings`, omp's `--hook`, codex's `-c hooks.*` — and
// all only ADD to the user's own configuration, which is never written. None holds a secret:
// the per-launch URL and bearer arrive in the harness's environment (KERMANYCH_NATIVE_URL /
// KERMANYCH_NATIVE_TOKEN), so every native session on this machine shares the same files.
// Written once per api process to a fixed temp path, like runtime/omp-mcp-bridge.ts. The one
// per-session, secret-holding file — claude's session-browser `--mcp-config` — is at the bottom.
import { createHash } from "node:crypto";
import { chmod, mkdir, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { MCP_TOKEN_ENV } from "../runtime/omp-mcp-bridge";

export const NATIVE_URL_ENV = "KERMANYCH_NATIVE_URL";
export const NATIVE_TOKEN_ENV = "KERMANYCH_NATIVE_TOKEN";

// The hook events Kermanych reads a claude session's status from (native-session.service.ts).
export const CLAUDE_HOOK_EVENTS = [
  "SessionStart",
  "UserPromptSubmit",
  "PreToolUse",
  "PostToolUse",
  "PermissionRequest",
  "Notification",
  "Stop",
] as const;

// The hook's stdin (claude's JSON for the event) is forwarded verbatim. `-o /dev/null`
// matters: stdout of a `UserPromptSubmit`/`SessionStart` hook is added to the agent's context.
// `|| true` and no output mean the hook never blocks anything and never decides a
// `PermissionRequest`/`PreToolUse`. `-m 3` bounds a wedged api well inside the 5 s timeout.
export const CLAUDE_HOOK_COMMAND =
  `curl -sS -m 3 -o /dev/null -H "Authorization: Bearer $${NATIVE_TOKEN_ENV}" -H "Content-Type: application/json" ` +
  `--data-binary @- "$${NATIVE_URL_ENV}/claude" || true`;

export function claudeSettings(): { hooks: Record<string, { hooks: { type: "command"; command: string; timeout: number }[] }[]> } {
  const hooks: Record<string, { hooks: { type: "command"; command: string; timeout: number }[] }[]> = {};
  for (const event of CLAUDE_HOOK_EVENTS) hooks[event] = [{ hooks: [{ type: "command", command: CLAUDE_HOOK_COMMAND, timeout: 5 }] }];
  return { hooks };
}

// Plain ESM JavaScript: omp loads it with no build step. Inert unless both env vars are set
// (a hand-started omp that happens to load it does nothing), silent for subagents, and it can
// never throw into omp: every handler and every POST is caught. Posts are chained so the api
// receives `tool` before its `tool_end` even when a request is slow.
export const OMP_EXTENSION_SOURCE = `// Generated by Kermanych (apps/api/src/native/native-hooks.ts) — do not edit.
const url = process.env.${NATIVE_URL_ENV};
const token = process.env.${NATIVE_TOKEN_ENV};
let chain = Promise.resolve();

function post(body) {
  chain = chain
    .then(() =>
      fetch(url + "/omp", {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: "Bearer " + token },
        body: JSON.stringify(body),
        signal: AbortSignal.timeout(3000),
      }),
    )
    .then(
      () => undefined,
      () => undefined,
    );
}

function lastAssistant(messages) {
  if (!Array.isArray(messages)) return undefined;
  for (let i = messages.length - 1; i >= 0; i--) if (messages[i] && messages[i].role === "assistant") return messages[i];
  return undefined;
}

export default function (pi) {
  if (!url || !token) return;
  const on = (name, fn) =>
    pi.on(name, (event, ctx) => {
      try {
        if (ctx && ctx.agent && ctx.agent.kind === "sub") return;
        fn(event || {}, ctx);
      } catch {}
    });
  const session = (ctx) => {
    const sm = ctx && ctx.sessionManager;
    if (!sm) return;
    const sessionFile = sm.getSessionFile && sm.getSessionFile();
    const sessionId = sm.getSessionId && sm.getSessionId();
    if (sessionFile || sessionId) post({ event: "session", sessionId, sessionFile });
  };
  on("session_start", (_e, ctx) => session(ctx));
  on("session_switch", (_e, ctx) => session(ctx));
  on("agent_start", (_e, ctx) => {
    session(ctx);
    post({ event: "working" });
  });
  on("tool_execution_start", (e) => post({ event: "tool", toolName: String(e.toolName || "") }));
  on("tool_execution_end", () => post({ event: "tool_end" }));
  on("tool_approval_requested", () => post({ event: "blocked" }));
  on("tool_approval_resolved", () => post({ event: "unblocked" }));
  on("agent_end", (e) => {
    const last = lastAssistant(e.messages);
    if (last && last.stopReason === "error") post({ event: "error", message: String(last.errorMessage || "") });
    else post({ event: "idle" });
  });
}
`;

// Rewritten on every launch rather than memoized: the content is tiny and fixed, and a temp
// directory the OS swept while the api ran must not leave a launch pointing at a missing file.
// `mode` is for a file that holds a secret: set at creation and re-applied to an older file.
async function writeHookFile(name: string, content: string, mode?: number): Promise<string> {
  const dir = join(tmpdir(), "kermanych-native");
  await mkdir(dir, { recursive: true });
  const path = join(dir, name);
  await writeFile(path, content, { encoding: "utf8", ...(mode === undefined ? {} : { mode }) });
  if (mode !== undefined) await chmod(path, mode);
  return path;
}

export function claudeSettingsPath(): Promise<string> {
  return writeHookFile("claude-settings.json", JSON.stringify(claudeSettings(), null, 2));
}

export function ompExtensionPath(): Promise<string> {
  return writeHookFile("omp-native.js", OMP_EXTENSION_SOURCE);
}

// The hook events Kermanych reads a codex session's status from. `Interrupt` exists from codex
// 0.163; an older codex ignores the unknown key.
export const CODEX_HOOK_EVENTS = ["SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "PermissionRequest", "Stop", "Interrupt"] as const;

// codex's hook: the event's stdin JSON forwarded verbatim, as for claude. A script rather than an
// inline command, so the env expansion and `|| true` never depend on how codex runs a hook
// command. Nothing on stdout (plain stdout of SessionStart/UserPromptSubmit is injected into the
// model's context) and always exit 0 (exit 2 blocks a prompt or denies a tool). Inert without the
// two variables, so a hand-started codex that somehow carries the hook does nothing. `-m 2`
// stays inside the hook's 3 s timeout.
export const CODEX_HOOK_SOURCE = `#!/bin/sh
# Generated by Kermanych (apps/api/src/native/native-hooks.ts) — do not edit.
[ -n "$${NATIVE_URL_ENV}" ] && [ -n "$${NATIVE_TOKEN_ENV}" ] || exit 0
curl -sS -m 2 -o /dev/null -H "Authorization: Bearer $${NATIVE_TOKEN_ENV}" -H "Content-Type: application/json" --data-binary @- "$${NATIVE_URL_ENV}/codex" >/dev/null 2>&1
exit 0
`;

export function codexHookPath(): Promise<string> {
  return writeHookFile("codex-hook.sh", CODEX_HOOK_SOURCE, 0o755);
}

// The layer name codex gives `-c` overrides; trust state keys on it.
const CODEX_FLAGS_LAYER = "/<session-flags>/config.toml";

// codex's `trusted_hash` for a hook (codex-rs/hooks/src/engine/discovery.rs `hook_hash` +
// codex-rs/config/src/fingerprint.rs `version_for_toml`): sha256 of the compact JSON, keys
// sorted, of the normalized identity `{event_name, hooks: [handler]}` (no matcher here). The
// literal below keeps its keys sorted. Internal to codex: if a version changes it, the
// «Hooks need review» modal shows in the session's terminal — visible, never silent.
export function codexHookHash(event: string, command: string, timeout: number): string {
  const identity = `{"event_name":${JSON.stringify(event)},"hooks":[{"async":false,"command":${JSON.stringify(command)},"timeout":${timeout},"type":"command"}]}`;
  return `sha256:${createHash("sha256").update(identity).digest("hex")}`;
}

// Every codex hook's timeout, in seconds. codex clamps `Interrupt` and `SessionEnd` hooks to 3 s
// and hashes the clamped value, so a larger one would leave those hooks untrusted; 3 for all
// keeps one handler and one hash rule.
const CODEX_HOOK_TIMEOUT_S = 3;

// The `-c` overrides every codex launch carries (docs/specs/2026-10-16-native-codex.md → D3–D5,
// D9). Values are TOML; JSON string literals are valid TOML basic strings.
// - `projects={…}` trusts the working directory for this run only. Only the inline-table form
//   skips the folder-trust dialog; `root` must be the realpath (codex compares realpaths).
// - one `hooks.<Event>` per event, and `hooks.state` pre-trusting exactly those handlers, so no
//   review modal shows and nothing is written to ~/.codex/config.toml.
// - the session MCP server reads its bearer from the pty env, never from argv.
export function codexConfigArgs(root: string, hook: string, mcp?: { name: string; url: string }): string[] {
  const command = `'${hook.replace(/'/g, `'\\''`)}'`;
  const handler = `{type="command",command=${JSON.stringify(command)},timeout=${CODEX_HOOK_TIMEOUT_S},async=false}`;
  const args = ["-c", `projects={${JSON.stringify(root)}={trust_level="trusted"}}`];
  const state: string[] = [];
  for (const event of CODEX_HOOK_EVENTS) {
    // codex's key label for an event: `SessionStart` → `session_start`.
    const label = event.replace(/[A-Z]/g, (c, i: number) => (i ? "_" : "") + c.toLowerCase());
    args.push("-c", `hooks.${event}=[{hooks=[${handler}]}]`);
    state.push(`${JSON.stringify(`${CODEX_FLAGS_LAYER}:${label}:0:0`)}={trusted_hash=${JSON.stringify(codexHookHash(label, command, CODEX_HOOK_TIMEOUT_S))}}`);
  }
  args.push("-c", `hooks.state={${state.join(",")}}`);
  if (mcp) args.push("-c", `mcp_servers.${mcp.name}={url=${JSON.stringify(mcp.url)},bearer_token_env_var=${JSON.stringify(MCP_TOKEN_ENV)}}`);
  return args;
}

// The session browser's MCP server for a native claude (`--mcp-config`,
// docs/specs/2026-10-05-embedded-browser.md). Unlike the files above it holds the
// session's bearer — claude reads MCP headers only from config, not from its environment — so
// it is one file per session, readable by the operator alone.
export function claudeMcpConfigPath(sessionId: string, server: { name: string; url: string; token: string }): Promise<string> {
  const config = { mcpServers: { [server.name]: { type: "http", url: server.url, headers: { Authorization: `Bearer ${server.token}` } } } };
  return writeHookFile(`mcp-${sessionId}.json`, JSON.stringify(config, null, 2), 0o600);
}
